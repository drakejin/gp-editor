// Writes src/score/symbols/glyph-ink.ts from glyph-ink's output (stdin). Usage: node write-table.mjs <out.ts>
import { readFileSync, writeFileSync } from 'node:fs';

const rows = readFileSync(0, 'utf8').trim().split('\n').map((line) => line.split(' '));
const entries = rows.map(([hex, top, bottom]) => `  0x${hex}: [${Number(top)}, ${Number(bottom)}],`);
writeFileSync(process.argv[2], `// Generated by scripts/glyph-ink/run.sh from macos/GPEditor-macOS/Fonts/Bravura.otf — do not edit; run it again when an
// engraver draws a new glyph.

/**
 * How far each music glyph the engravers draw reaches above (+) and below (−) its baseline, in ems of the music font
 * (one em = the size it is drawn at), as CoreText draws Bravura. \`ink.ts\` reads it.
 */
export const GLYPH_INK: Readonly<Record<number, readonly [number, number]>> = {
${entries.join('\n')}
};
`);
