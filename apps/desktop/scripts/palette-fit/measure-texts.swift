// Measures the edition palette's texts with AppKit's system font — what React Native's Text draws with on the Mac
// (Hangul from the system's fallback font, as there) — and writes them as a TypeScript table.
// Usage: measure-texts <texts.json> <out.ts>   (texts.json: [{ "text", "size", "weight": "semibold" | "bold" }])
import AppKit
import Foundation

struct TextRequest: Decodable {
  let text: String
  let size: Double
  let weight: String
}

func width(of request: TextRequest) -> Double {
  let weight: NSFont.Weight = request.weight == "bold" ? .bold : .semibold
  let font = NSFont.systemFont(ofSize: CGFloat(request.size), weight: weight)
  return Double((request.text as NSString).size(withAttributes: [.font: font]).width)
}

/** A size as JavaScript writes a number: "11", "10.5" (whatever the locale). */
func sizeText(_ size: Double) -> String {
  size == size.rounded() ? String(Int(size)) : String(size)
}

/** A TypeScript string literal (JSON's escaping is TypeScript's). */
func literal(_ text: String) -> String {
  let data = try! JSONSerialization.data(withJSONObject: [text], options: [.withoutEscapingSlashes])
  let array = String(data: data, encoding: .utf8)!
  return String(array.dropFirst().dropLast())
}

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
  FileHandle.standardError.write("usage: measure-texts <texts.json> <out.ts>\n".data(using: .utf8)!)
  exit(1)
}
let requests = try JSONDecoder().decode([TextRequest].self, from: Data(contentsOf: URL(fileURLWithPath: arguments[1])))
let rows = requests
  .map { request -> (String, Double) in ("\(sizeText(request.size))/\(request.weight)/\(request.text)", width(of: request)) }
  .sorted { $0.0 < $1.0 }
  .map { "  \(literal($0.0)): \(String(format: "%.2f", $0.1)),\n" }
let version = ProcessInfo.processInfo.operatingSystemVersionString
let source = """
// Generated by scripts/palette-fit/run.sh with AppKit's system font (\(version)) — do not edit; run it again when a
// palette face or key changes (__tests__/palette-fit.test.ts names the texts it lacks).

/** Widths in points of the texts the edition palette draws, by "size/weight/text" (test-support/palette-fit.ts). */
export const PALETTE_TEXT_WIDTHS: Readonly<Record<string, number>> = {
\(rows.joined())};

"""
try source.write(toFile: arguments[2], atomically: true, encoding: .utf8)
